"""ROM-free tests for the verified 4bpp sprite patch pipeline.

Run: python3 -m unittest discover -s tests -p 'sprite_override_test.py' -v
Only synthetic memory buffers are used. No game ROM, BIOS, or art.
"""
import hashlib
from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from create_sprite_override import (  # noqa: E402
    encode_4bpp, patch_4bpp, ips_from_diff, USA_SIZE
)


def apply_ips(original, patch):
    assert patch[:5] == b"PATCH" and patch[-3:] == b"EOF"
    result = bytearray(original)
    at = 5
    while at < len(patch) - 3:
        offset = int.from_bytes(patch[at:at + 3], "big")
        count = int.from_bytes(patch[at + 3:at + 5], "big")
        at += 5
        assert count > 0  # no RLE records generated by our pipeline
        result[offset:offset + count] = patch[at:at + count]
        at += count
    assert at == len(patch) - 3
    return bytes(result)


class SpriteOverrideTests(unittest.TestCase):
    def make_rom(self, tiles, *, duplicate=False):
        rom = bytearray(b"\xff" * USA_SIZE)
        rom[0xAC:0xB0] = b"BDVE"
        rom[0x2000:0x2000 + len(tiles)] = tiles
        if duplicate:
            rom[0x4000:0x4000 + len(tiles)] = tiles
        return bytes(rom)

    def test_encode_4bpp_low_even_high_odd_and_tile_order(self):
        img = bytes([((x + y) % 16) for y in range(8)
                     for x in range(16)])
        got = encode_4bpp(16, 8, img)
        self.assertEqual(len(got), 64)
        self.assertEqual(got[0], 0x10)
        self.assertEqual(got[1], 0x32)
        self.assertEqual(got[32], 0x98)  # second tile: pixel 8, 9
        with self.assertRaises(ValueError):
            encode_4bpp(9, 8, bytes(72))
        with self.assertRaises(ValueError):
            encode_4bpp(8, 8, bytes([16] * 64))

    def test_unique_match_data_only_patch(self):
        original = bytes(range(64))
        changed = bytearray(original)
        changed[0:4] = b"\x00\x01\x00\x03"
        changed[20] = 5
        changed[63] = 9
        rom = self.make_rom(original)
        copy_sha1 = hashlib.sha1(rom).hexdigest()
        ips, report = patch_4bpp(rom, original, bytes(changed),
                                 expected_sha1=copy_sha1)
        self.assertEqual(report["offset_hex"], "0x002000")
        self.assertEqual(report["tile_count"], 2)
        target = apply_ips(rom, ips)
        self.assertEqual(target[0x2000:0x2040], bytes(changed))
        self.assertEqual(target[:0x2000], rom[:0x2000])
        self.assertEqual(target[0x2040:], rom[0x2040:])
        self.assertEqual(rom[0x2000:0x2040], original)

    def test_refuse_unknown_revision(self):
        tile = bytes(range(64))
        rom = self.make_rom(tile)
        with self.assertRaisesRegex(ValueError, "SHA-1 mismatch"):
            patch_4bpp(rom, tile, bytes([2] * 64))

    def test_refuse_ambiguous_match_without_explicit_offset(self):
        original = bytes(range(64))
        rom = self.make_rom(original, duplicate=True)
        digest = hashlib.sha1(rom).hexdigest()
        with self.assertRaisesRegex(ValueError, "multiple ROM offsets"):
            patch_4bpp(rom, original, bytes([7] * 64),
                       expected_sha1=digest)
        _, report = patch_4bpp(rom, original, bytes([7] * 64),
                               expected_sha1=digest, offset=0x4000)
        self.assertEqual(report["offset_hex"], "0x004000")

    def test_refuse_bad_length_mismatch_and_header(self):
        old = bytes(range(64))
        new = bytes([3] * 64)
        rom = self.make_rom(old)
        digest = hashlib.sha1(rom).hexdigest()
        with self.assertRaisesRegex(ValueError, "exactly the same number"):
            patch_4bpp(rom, old, new[:32], expected_sha1=digest)
        with self.assertRaisesRegex(ValueError, "selected offset"):
            patch_4bpp(rom, old, new, expected_sha1=digest, offset=0x3000)
        with self.assertRaisesRegex(ValueError, "invalid source range"):
            patch_4bpp(rom, old, new, expected_sha1=digest, offset=0)
        with self.assertRaises(ValueError):
            ips_from_diff(0x100, old, new[:-1])

    def test_identical_and_uncompressed_missing_are_rejected(self):
        old = bytes(range(64))
        rom = self.make_rom(old)
        digest = hashlib.sha1(rom).hexdigest()
        with self.assertRaisesRegex(ValueError, "no different pixel"):
            patch_4bpp(rom, old, old, expected_sha1=digest)
        with self.assertRaisesRegex(ValueError, "not found"):
            patch_4bpp(rom, bytes([4] * 64), bytes([6] * 64),
                       expected_sha1=digest)


if __name__ == "__main__":
    unittest.main()
